export type MissingPermissionDependency = {
  permission: PermissionKey;
  requiredPermission: PermissionKey;
};

export function getMissingModeratorPermissionDependencies(
  permissions: Iterable<PermissionKey>,
): MissingPermissionDependency[] {
  const selected = new Set(permissions);

  return Object.entries(MODERATOR_PERMISSION_DEPENDENCIES).flatMap(
    ([permission, requiredPermission]) =>
      selected.has(permission as PermissionKey) &&
      !selected.has(requiredPermission)
        ? [
            {
              permission: permission as PermissionKey,
              requiredPermission,
            },
          ]
        : [],
  );
}

