export const MODERATOR_PERMISSION_GROUPS = PERMISSION_GROUPS.flatMap(
  (group) => {
    if (group.key === "users") return [];

    const permissions = group.permissions.filter(
      (permission) => !MODERATOR_EXCLUDED_PERMISSIONS.has(permission),
    );

    return permissions.length > 0 ? [{ ...group, permissions }] : [];
  },
);

export const MODERATOR_MANAGEABLE_PERMISSIONS: PermissionKey[] =
  MODERATOR_PERMISSION_GROUPS.flatMap((group) => [...group.permissions]);

